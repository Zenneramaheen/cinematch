def build_csv(out_path: Path) -> None:
    """Validate the movie list and write it to movies.csv."""
    seen = set()
    for title, year, genres, rating, overview in MOVIES:
        key = title.strip().lower()
        if key in seen:
            raise ValueError(f"Duplicate title: {title}")
        seen.add(key)
        assert isinstance(year, int) and 1900 <= year <= 2030, title
        assert 0 < rating <= 10, title
        assert genres and overview, title
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["title", "year", "genres", "overview", "rating"])
        for title, year, genres, rating, overview in MOVIES:
            w.writerow([title, year, genres, overview, rating])
    print(f"Wrote {len(MOVIES)} movies -> {out_path}")


if __name__ == "__main__":
    build_csv(Path(__file__).parent / "movies.csv")
